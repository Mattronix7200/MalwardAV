namespace Malward.NetworkScanner.AdBlock;

public static class AdCollapse
{
    public const string ElementId = "malward-collapse";

    public static string Script(int maxSelectors = 400) =>
        "<script id=\"" + ElementId + "\">(function(){"
        + "if(window.__mwCol)return;window.__mwCol=1;"
        + "var MAXUP=3,MAXSEL=" + maxSelectors + ",runs=0,MAXRUNS=12;"
        + "var SKIP={BODY:1,HTML:1,MAIN:1,HEADER:1,NAV:1,FOOTER:1,ARTICLE:1,SECTION:1,"
        + "FORM:1,TABLE:1,TBODY:1,TR:1,UL:1,OL:1,HEAD:1};"
        + "function vis(e){try{var s=getComputedStyle(e);"
        + "return s.display!=='none'&&s.visibility!=='hidden'&&s.opacity!=='0';}catch(x){return true;}}"
        + "function solid(e){if(!e)return false;"
        + "if(e.nodeType===3)return e.textContent.trim().length>0;"
        + "if(e.nodeType!==1)return false;if(!vis(e))return false;"
        + "var t=e.tagName;"
        + "if(t==='IMG'||t==='VIDEO'||t==='AUDIO'||t==='CANVAS'||t==='SVG'||t==='IFRAME'"
        + "||t==='INPUT'||t==='BUTTON'||t==='SELECT'||t==='TEXTAREA'||t==='EMBED'||t==='OBJECT')return true;"
        + "var n=e.childNodes;for(var i=0;i<n.length;i++){var c=n[i];"
        + "if(c.nodeType===3){if(c.textContent.trim().length>0)return true;}"
        + "else if(c.nodeType===1&&solid(c))return true;}return false;}"
        + "function hideUp(start){var e=start.parentElement,n=0;"
        + "while(e&&n<MAXUP&&!SKIP[e.tagName]){"
        + "if(e.getAttribute('data-mw-col'))return;"
        + "if(solid(e))return;"
        + "var r;try{r=e.getBoundingClientRect();}catch(x){return;}"
        + "if(r.height<=0&&r.width<=0)return;"
        + "if(r.height>700)return;"
        + "e.setAttribute('data-mw-col','1');"
        + "var S=window.__abStyle;"
        + "if(!(S&&S.apply(e,'display:none!important')))"
        + "e.style.setProperty('display','none','important');"
        + "e=e.parentElement;n++;}}"
        + "function selectors(){var st=document.getElementById('malward-cosmetic');"
        + "if(!st)return null;var txt=st.textContent||'';"
        + "var body=txt.replace(/\\{[^}]*\\}/g,',');"
        + "var list=body.split(',').map(function(s){return s.trim();})"
        + ".filter(function(s){return s.length>0;});"
        + "if(list.length===0||list.length>MAXSEL)return null;return list;}"
        + "var sels=null,ready=false;"
        + "function sweep(){if(runs++>MAXRUNS)return;"
        + "if(!ready){sels=selectors();ready=true;}"
        + "if(!sels)return;"
        + "for(var i=0;i<sels.length;i++){var found;"
        + "try{found=document.querySelectorAll(sels[i]);}catch(x){continue;}"
        + "for(var j=0;j<found.length;j++){if(!vis(found[j]))hideUp(found[j]);}}}"
        + "function later(){clearTimeout(window.__mwColT);"
        + "window.__mwColT=setTimeout(sweep,250);}"
        + "if(document.readyState==='loading')"
        + "document.addEventListener('DOMContentLoaded',later);else later();"
        + "window.addEventListener('load',later);"
        + "if(window.__abObs)window.__abObs(later);"
        + "else{try{new MutationObserver(later).observe(document.documentElement,"
        + "{subtree:true,childList:true});}catch(x){}}"
        + "})();</script>";
}
